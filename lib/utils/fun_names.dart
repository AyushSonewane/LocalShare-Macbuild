/// Returns a fun name deterministically derived from [deviceId].
/// The same device ID always produces the same name.
String pickFunName(String deviceId) {
  // Use a simple hash of the device ID to index into the list
  int hash = 0;
  for (final ch in deviceId.codeUnits) {
    hash = (hash * 31 + ch) & 0x7FFFFFFF;
  }
  return kFunNames[hash % kFunNames.length];
}
